}

-- Game client locale -> addon language
local FROM_LOCALE = {
    frFR = "fr", deDE = "de", esES = "es", esMX = "es",
    ptBR = "pt", ptPT = "pt", ruRU = "ru", itIT = "it",
}

function ns.DefaultLanguage()
    return FROM_LOCALE[GetLocale()] or "en"
end

function ns.LanguageName(key)
    for _, entry in ipairs(ns.LANGUAGES) do
        if entry.key == key then return entry.name end
    end
    return key
end

-- The gothic title font has no Cyrillic outside the Russian client
function ns.UsesLatinFont()
    local lang = (ns.db and ns.db.language) or ns.DefaultLanguage()
    return lang ~= "ru" or GetLocale() == "ruRU"
end

-- Translated text for a key, in the chosen language
function ns.T(key)
    local lang = (ns.db and ns.db.language) or ns.DefaultLanguage()
    local strings = L[lang] or L.en
    return strings[key] or L.en[key] or key
end
